def circle_geom(pnt, w, h):
    """panorama circle geometry generator, used for direction arrow creation"""

    list_circle =[]
    for i in range(0,36):
        an =math.radians(i * 10)
        np_x = pnt.x() + (w* math.sin(an))
        np_y = pnt.y() + (h* math.cos(an))
        pnt_new = QgsPointXY(np_x,np_y) 
        list_circle.append(pnt_new) 
    ellipse_geom = QgsGeometry.fromPolygonXY([list_circle])
    return ellipse_geom

def read_in_chunks(file_object, chunk_size=None):
    """Read file by chunk index """
    while True:
        data = file_object.read(chunk_size)
        if not data:
            break
        yield data

class GetPanorama(QWidget):
    """Get panorama image from web or local storage
    depending on method
    """

    def __init__(self, parent):
        super().__init__()
        self.main_app = parent

    def get_pano_file(self, file_url, method):
        """Selecting a method to get an image """
        if method == "download":
            result = self.download(file_url)
        else:
            result = self.copy_file(file_url)
        return result

    def download(self, url):
        """Web loader which also writes file chunk by chunk """
        self.main_app.pbar.setDisabled(False)
        r = requests.get(url, allow_redirects=True, stream=True, timeout=120)
        if r.status_code != 200:
            self.main_app.notify("Download failed (HTTP {}): {}".format(r.status_code, url))
            return False
        total_length = int(r.headers.get("content-length") or 0)
        file_name = os.path.join(base_folder, "image.JPG")
        with open(file_name, "wb") as f:
            p_step = 100 / total_length * 4096 if total_length else 0
            counter = 0
            for data in r.iter_content(chunk_size=4096):
                counter += p_step
                f.write(data)
                self.main_app.pbar.setValue(min(int(counter), 100))
                QtCore.QCoreApplication.processEvents()
        self.main_app.pbar.setValue(0)
        self.main_app.pbar.setDisabled(True)
        return True

    def copy_file(self, file_in):
        """File copier, also uses chunk writing method """
        self.main_app.pbar.setDisabled(False)
        file_out = os.path.join(base_folder, "image.JPG")
        file_stats = os.stat(file_in)
        size_b = file_stats.st_size
        ch_optimal_size = max(int(size_b / 100), 4096)
        p_step = 100 / size_b * ch_optimal_size if size_b else 100
        counter = 0
        open(file_out, "w").close()
        with open(file_in, "rb") as f:
            for piece in read_in_chunks(f, ch_optimal_size):
                with open(file_out, "ab") as fout:
                    fout.write(piece)
                counter += p_step
                self.main_app.pbar.setValue(min(int(counter), 100))
                QtCore.QCoreApplication.processEvents()
        self.main_app.pbar.setValue(0)
        self.main_app.pbar.setDisabled(True)
        return True

class QuietHandler(SimpleHTTPRequestHandler):
    """Web server handler, which will not write any message
    in python console. As a result, no need to open python console
    in QGIS in order to make plugin work
    """

    hub = None      # set per server (see HttpDaemon.run)
    bridge = None

    def log_message(self, format, *args):
        pass

    def do_GET(self):
        if self.hub is not None and handle_live_request(self, self.hub, self.bridge):
            return
        super().do_GET()

    def do_POST(self):
        if self.hub is not None and handle_live_request(self, self.hub, self.bridge):
            return
        self.send_error(405)

    def end_headers(self):
        # the panorama is always served as image.JPG, so never let the
        # embedded browser (or the system browser) cache it
        self.send_header("Cache-Control", "no-store, no-cache, must-revalidate, max-age=0")
        self.send_header("Pragma", "no-cache")
        self.send_header("Expires", "0")
        super().end_headers()

class HttpDaemon(QtCore.QThread):
    """Simple web server class
    """

    def __init__(self, parent, path):
        super().__init__()
        self.server_path = path
        self.server = None
        self.is_running = False
        self.server_host = self.find_free_ip(PORT)
        self.setTerminationEnabled(True)
        self.hub = LiveHub()          # external browser window channel
        self.bridge = LiveBridge()    # created here, so it lives in the main thread
        if not self.server_host:
            raise RuntimeError("Couldn't found free IP-address in 127.x.x.x ranges")
    
    @staticmethod
    def find_free_ip(port):
        """looking for a free local IP"""
        for i in range(1, 255):
            test_host = f"127.0.0.{i}"
            with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
                try:
                    s.bind((test_host, port))
                    return test_host  # if bind is ok, return it
                except OSError:
                    continue
        return None

    def run(self):
        # os.chdir(self.server_path)
        handler_cls = type("PanoHandler", (QuietHandler,), {"hub": self.hub, "bridge": self.bridge})
        handler = partial(handler_cls, directory=self.server_path)
        self.server = ThreadingHTTPServer((self.server_host, PORT), handler)
        self.server.daemon_threads = True  # open live streams never block shutdown
        self.is_running = True
        self.server.serve_forever()

    def stop(self):
        self.hub.close()  # ends the live streams; browser tabs show "not connected"
        if self.server:
            self.is_running = False
            try:
                self.server.shutdown()
            except:
                pass 
            try:
                self.server.socket.close()
            except:
                pass 
            try:
                self.server.server_close()
            except:
                pass 
            if not self.wait(500):
                self.terminate()
                self.wait()

    def stop_and_cleanup(self):
        """Full stop"""
        self.stop()
        
        # delete temp pano file
        image_path = os.path.join(self.server_path, "image.JPG")
        if os.path.exists(image_path):
            try:
                os.remove(image_path)
            except:
                pass

