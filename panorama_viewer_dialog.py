    def load_layers(self):
        """Update layer combobox"""
        self.layer_data = {
            lyr.id(): lyr
            for lyr in QgsProject.instance().mapLayers().values()
            if type(lyr) == QgsVectorLayer and lyr.isValid()
        }
        self.cmb_layers.clear()
        i = 0
        for layer_id, layer in self.layer_data.items():
            self.cmb_layers.addItem(layer.name())
            self.cmb_layers.setItemData(i, layer_id, Qt.ItemDataRole.ToolTipRole)
            self.cmb_layers.setItemData(i, layer)
            i += 1
        self.update_current_layer()

    def warning_message(self, err_text):
        """Custom warning message"""
        msg = QMessageBox()
        msg.warning(self, "Warning", err_text)
        return

    def update_current_layer(self):
        """Setting current layer and its fields from combobox value"""
        self.current_layer = self.cmb_layers.currentData()
        if self.current_layer:
            layer_fields = [
                f.name() for f in self.current_layer.fields() if is_string_field(f)
            ]
            
            self.cmb_fields.clear()
            self.direction_field.blockSignals(True)
            self.direction_field.clear()
            self.cmb_fields.addItems(layer_fields)
            self.direction_field.addItems(['- none -'] + self.current_layer.fields().names())
            self.direction_field.blockSignals(False)

        self.btn_find_panorama.setChecked(False)
        self.rubberBandArrow.reset()
       
    def reset_tr(self):
        """Reset server"""
        self.btn_find_panorama.setChecked(False)
        self.rubberBandArrow.reset()
        if self.httpd:
            self.httpd.stop()

    def get_pic(self):
        """Get pic attrs from selected point and proceed to view panorama"""
        
        if self.cmb_fields.currentText():
            field_idx = (
                self.current_layer.fields().names().index(self.cmb_fields.currentText())
            )
            selected_features = self.current_layer.selectedFeatures()
            if not selected_features:
                return
            self.rubberBandArrow.reset()
            
            self.pano_loaded = False
            if not selected_features:
                if not self.auto_update.isChecked():
                    self.warning_message("No items selected")
                return
            
            crs = self.current_layer.crs()
            tr=QgsProject.instance().transformContext()
            transform_crs = QgsCoordinateTransform(crs, QgsProject.instance().crs(), tr)

            current_feature = selected_features[0]
            cf_attr = current_feature.attributes()[field_idx]
            cf_geom = current_feature.geometry().centroid()
            cf_geom.transform(transform_crs)
            self.x = cf_geom.asPoint().x()
            self.y = cf_geom.asPoint().y()
            
            img_get = False
            angle_field = self.direction_field.currentText()
            angle = 0
            self.angle = 0
            if angle_field != '- none -':
                angle = current_feature[angle_field]
                try:
                    angle = float(angle)
                except:
                    angle = 0.0
                
                self.angle = angle
            
            # panorama path check: local / UNC paths, file://, smb:// and http(s)://
            source = pano_paths.resolve(cf_attr)
            self.current_title = os.path.basename(str(cf_attr or "").rstrip("/\\"))
            getter = GetPanorama(self)
            try:
                if source.kind == "local":
                    img_get = getter.get_pano_file(source.value, "copy")
                elif source.kind == "web":
                    img_get = getter.get_pano_file(source.value, "download")
                else:
                    self.notify(source.message)
            except Exception as e:  # network errors, permissions, disk full...
                img_get = False
                self.notify("Could not load the panorama: {}".format(e))
            finally:
                self.pbar.setValue(0)
                self.pbar.setDisabled(True)

            if img_get:
                self.angle = angle
                QApplication.processEvents()
                page = "index_{}.html".format(self.viewers.get(self.combo_viewer.currentText(), "pannellum"))
                url = "http://{}:{}/{}?angle={}&zoom={}&controls_visible={}".format(
                    self.httpd.server_host, PORT, page, self.angle, self.zoom, self.controls_visible)
                if self.view is None:
                    url += "&silent_mode=1"
                self.load_url(url)
            else:
                self.load_url("http://{}:{}/index_error.html".format(self.httpd.server_host, PORT))
            self.pano_loaded = True
            self.pbar.reset()

            return

